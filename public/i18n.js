const supported = ["zh", "en"];
const storageKey = "relay-locale";

/// 语言选择跟着账号走(服务端 profile 里存 locale),localStorage 只是本机缓存 ——
/// 换设备也要保持,这是工单明确要求的。第一次进来按浏览器语言猜。
function guess() {
  // 在 Node 里被测试直接 import 时没有 localStorage/navigator,这时不猜,按中文来。
  if (typeof localStorage === "undefined" || typeof navigator === "undefined") return "zh";
  const stored = localStorage.getItem(storageKey);
  if (supported.includes(stored)) return stored;
  /// 按偏好顺序取第一个认得出来的,不能「出现过中文就算中文」——
  /// navigator.languages 常是 ["en-US","en-AE","zh-Hans-AE"] 这样的混合列表,
  /// 那么判会把明明主语言是英文的人开成中文。
  const preferred = [navigator.language, ...(navigator.languages ?? [])]
    .filter(Boolean)
    .map((tag) => String(tag).toLowerCase());
  for (const tag of preferred) {
    if (tag.startsWith("zh")) return "zh";
    if (tag.startsWith("en")) return "en";
  }
  return "zh";
}

let locale = guess();

export function getLocale() {
  return locale;
}

/// 传给 toLocale* 的 BCP 47 标签。日期和数字不用自己翻,交给平台。
export function dateLocale() {
  return locale === "en" ? "en-GB" : "zh-CN";
}

export function t(key, values = []) {
  const table = dictionaries[locale];
  const template = table?.[key] ?? key;
  return template.replace(/\{(\d+)\}/g, (match, index) => {
    const value = values[Number(index)];
    return value === undefined || value === null ? "" : String(value);
  });
}

/// 静态 HTML 不改标记:直接扫文本节点和几个会被人读到的属性,命中字典就换。
/// key 就是中文原文,所以 index.html 里那 148 行文案一个字都不用动。
const attributeNames = ["placeholder", "title", "aria-label", "alt", "value"];

export function translateDom(root = document) {
  if (locale === "zh") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const pending = [];
  while (walker.nextNode()) pending.push(walker.currentNode);
  for (const node of pending) {
    const text = node.nodeValue;
    const trimmed = text.trim();
    if (!trimmed) continue;
    const translated = dictionaries[locale]?.[trimmed];
    if (translated) node.nodeValue = text.replace(trimmed, translated);
  }
  const scope = root.querySelectorAll ? root : document;
  for (const name of attributeNames) {
    for (const element of scope.querySelectorAll(`[${name}]`)) {
      // value 只翻按钮/提交这类展示用的,别动用户正在输入的内容
      if (name === "value" && !["button", "submit", "reset"].includes(element.type)) continue;
      const translated = dictionaries[locale]?.[element.getAttribute(name).trim()];
      if (translated) element.setAttribute(name, translated);
    }
  }
}

/// <html lang> 必须跟着切:屏幕阅读器和浏览器的「翻译此页」都看它。
export function applyLocale(next, { persistLocally = true } = {}) {
  locale = supported.includes(next) ? next : "zh";
  if (persistLocally && typeof localStorage !== "undefined") localStorage.setItem(storageKey, locale);
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale === "en" ? "en" : "zh-CN";
  }
  return locale;
}

